export const TSUMS: Tsum[] = RAW.map(([name, emoji], i) => ({
  id: `tsum-${i + 1}`,
  name,
  emoji,
  hue: (i * 47) % 360,
}));

export function tsumLevel(tsum: Tsum, maxed: boolean): number {
  if (maxed) return 50;
  let h = 0;
  for (const c of tsum.id) h = (h * 31 + c.charCodeAt(0)) >>> 0;
  return (h % 49) + 1;
}
